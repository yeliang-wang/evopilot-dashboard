#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const root = process.cwd();
const packageJson = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const version = packageJson.version;

function main(argv) {
  if (has(argv, "--help") || has(argv, "-h")) {
    printHelp();
    return;
  }

  const args = parseArgs(argv);
  const targetDir = path.resolve(args.dir);
  fs.mkdirSync(targetDir, { recursive: true });
  writeFile(targetDir, "compose.yaml", composeYaml(args), args.force);
  writeFile(targetDir, "README.md", readme(args), args.force);
  writeFile(targetDir, "verify.sh", verifyScript(args), args.force, 0o755);

  if (args.start) {
    execFileSync("docker", ["compose", "up", "-d"], { cwd: targetDir, stdio: "inherit" });
    if (!args.skipVerify) {
      execFileSync("bash", [path.join(targetDir, "verify.sh")], { cwd: targetDir, stdio: "inherit" });
    }
    printStarted(targetDir, args);
  } else {
    printNextSteps(targetDir, args);
  }
}

function parseArgs(argv) {
  const get = (name, fallback) => {
    const index = argv.indexOf(name);
    if (index >= 0) {
      const value = argv[index + 1];
      if (!value || value.startsWith("-")) fail(`${name} requires a value`);
      return value;
    }
    const prefix = `${name}=`;
    const match = argv.find((item) => item.startsWith(prefix));
    return match ? match.slice(prefix.length) : fallback;
  };

  return {
    dir: get("--dir", "evopilot-dashboard-run"),
    image: get("--image", `ghcr.io/yeliang-wang/evopilot-dashboard:${version}`),
    apiUrl: get("--api-url", "http://host.docker.internal:19876"),
    network: get("--network", ""),
    port: get("--port", "8080"),
    force: has(argv, "--force"),
    start: has(argv, "--start"),
    skipVerify: has(argv, "--skip-verify")
  };
}

function has(argv, flag) {
  return argv.includes(flag);
}

function writeFile(targetDir, relativePath, content, force, mode) {
  const filePath = path.join(targetDir, relativePath);
  if (fs.existsSync(filePath) && !force) {
    fail(`${relativePath} already exists in ${targetDir}. Re-run with --force to overwrite generated files.`);
  }
  fs.writeFileSync(filePath, content.endsWith("\n") ? content : `${content}\n`, { mode });
}

function composeYaml(args) {
  const serviceNetwork = args.network
    ? `    networks:
      - evopilot-control-plane
`
    : "";
  const networks = args.network
    ? `
networks:
  evopilot-control-plane:
    name: "\${EVOPILOT_DOCKER_NETWORK:-${args.network}}"
    external: true
`
    : "";
  return `name: evopilot-dashboard

services:
  evopilot-dashboard:
    image: \${EVOPILOT_DASHBOARD_IMAGE:-${args.image}}
    ports:
      - "\${EVOPILOT_DASHBOARD_PORT:-${args.port}}:8080"
    environment:
      EVOPILOT_API_BASE_URL: "\${EVOPILOT_API_BASE_URL:-${args.apiUrl}}"
    extra_hosts:
      - "host.docker.internal:host-gateway"
${serviceNetwork}    healthcheck:
      test: ["CMD-SHELL", "wget -qO- http://127.0.0.1:8080/health >/dev/null"]
      interval: 20s
      timeout: 5s
      retries: 10
    restart: unless-stopped
${networks}
`;
}

function readme(args) {
  return `# EvoPilot Dashboard Run Directory

Generated by \`npm run dashboard:run\`.

## Start

\`\`\`bash
docker compose up -d
./verify.sh
\`\`\`

## Runtime

- Dashboard: http://127.0.0.1:${args.port}
- EvoPilot API: ${args.apiUrl}
- Docker network: ${args.network || "default"}
- Image: ${args.image}

Dashboard remains a browser HTTP client. EvoPilot API is the system of record for auth, tenant/workspace scope, projects, harness bindings, loops, evidence, audit, release decisions, and credentials.
`;
}

function verifyScript(args) {
  return `#!/usr/bin/env bash
set -euo pipefail

curl -fsS "http://127.0.0.1:${args.port}/health" >/dev/null
curl -fsSI "http://127.0.0.1:${args.port}/" >/dev/null

echo "EvoPilot Dashboard is reachable."
`;
}

function printHelp() {
  console.log(`EvoPilot Dashboard runner

Usage:
  npm run dashboard:run -- [--dir evopilot-dashboard-run] [--api-url http://127.0.0.1:19876] [--network evopilot_default] [--port 8080] [--start]

Options:
  --dir <path>      Output directory. Default: evopilot-dashboard-run
  --api-url <url>   EvoPilot API URL from the Dashboard container. Default: http://host.docker.internal:19876
  --image <image>   Dashboard image. Default: ghcr.io/yeliang-wang/evopilot-dashboard:${version}
  --network <name>  Existing Docker network for API service discovery
  --port <port>     Host Dashboard port. Default: 8080
  --start           Run docker compose up -d after generating files
  --skip-verify     Skip verify.sh after --start
  --force           Overwrite generated files
`);
}

function printNextSteps(targetDir, args) {
  const displayPath = targetDir.startsWith(os.homedir()) ? targetDir.replace(os.homedir(), "~") : targetDir;
  console.log(`EvoPilot Dashboard run directory generated in ${displayPath}

Next:
  cd ${shellQuote(targetDir)}
  docker compose up -d
  ./verify.sh

Dashboard: http://127.0.0.1:${args.port}
`);
}

function printStarted(targetDir, args) {
  const displayPath = targetDir.startsWith(os.homedir()) ? targetDir.replace(os.homedir(), "~") : targetDir;
  console.log(`EvoPilot Dashboard started from ${displayPath}

Dashboard: http://127.0.0.1:${args.port}
`);
}

function shellQuote(value) {
  return `'${value.replace(/'/g, "'\\''")}'`;
}

function fail(message) {
  console.error(`evopilot-dashboard-run: ${message}`);
  process.exit(1);
}

main(process.argv.slice(2));
